"""Resize full-size originals into web-ready WebP files.

Reads every image in originals/, writes public/img/<name>.webp, and records
each output's dimensions in src/data/image-sizes.ts so <img> tags can reserve
space before the image loads.

Usage: python3 scripts/optimize_images.py   (requires Pillow)
"""
from pathlib import Path

from PIL import Image, ImageOps

ROOT = Path(__file__).resolve().parent.parent
SRC = ROOT / "originals"
OUT = ROOT / "public" / "img"
SIZES = ROOT / "src" / "data" / "image-sizes.ts"

DEFAULT_MAX_EDGE = 1600
MAX_EDGE = {"hero-bg": 2400}  # full-screen background needs more pixels
QUALITY = 80

OUT.mkdir(parents=True, exist_ok=True)
sizes = {}
for path in sorted(SRC.iterdir()):
    if path.suffix.lower() not in {".jpg", ".jpeg", ".png"}:
        continue
    out = OUT / f"{path.stem}.webp"
    img = ImageOps.exif_transpose(Image.open(path)).convert("RGB")
    edge = MAX_EDGE.get(path.stem, DEFAULT_MAX_EDGE)
    img.thumbnail((edge, edge), Image.LANCZOS)
    if not out.exists() or out.stat().st_mtime < path.stat().st_mtime:
        img.save(out, "WEBP", quality=QUALITY, method=6)
        print(f"{path.name} -> {out.relative_to(ROOT)} ({out.stat().st_size // 1024} KB)")
    sizes[path.stem] = img.size

lines = [f"  '{name}': [{w}, {h}]," for name, (w, h) in sizes.items()]
SIZES.write_text(
    "// Generated by scripts/optimize_images.py. Do not edit by hand.\n"
    "export const imageSizes: Record<string, [number, number]> = {\n"
    + "\n".join(lines)
    + "\n};\n"
)
print(f"Wrote {len(sizes)} sizes to {SIZES.relative_to(ROOT)}")
